#!/usr/bin/env python3
"""Export thesis tables from recorded public-data aggregate metrics only.

Run from the repository root:
    python3 scripts/export_thesis_tables.py --config configs/default.yaml

No drawing, cache, split manifest or company data is opened.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml


def number(value: int | float) -> str:
    return rf"\num{{{value}}}"


def percentage(value: float) -> str:
    return rf"\num{{{value * 100:.2f}}}\%"


def write_table(
    destination: Path,
    columns: str,
    headers: list[str],
    rows: list[list[str]],
    sources: list[str],
) -> None:
    if any(len(row) != len(headers) for row in rows):
        raise ValueError(f"Inconsistent column count: {destination}")
    lines = ["% Generated by scripts/export_thesis_tables.py; do not edit."]
    lines.extend(f"% source: {source}" for source in sources)
    lines.extend([rf"\begin{{tabular}}{{{columns}}}", r"\toprule"])
    lines.append(" & ".join(headers) + r" \\")
    lines.append(r"\midrule")
    lines.extend(" & ".join(row) + r" \\" for row in rows)
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(destination)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    args = parser.parse_args()
    config = yaml.safe_load(args.config.read_text(encoding="utf-8"))
    output = Path(config["output"]["tables_dir"])
    run_root = Path(config["output"]["runs_dir"])
    selected = config["thesis_tables"]
    paths = {
        name: run_root / selected[name] / "metrics.json"
        for name in ("parse_run", "split_audit_run", "class_audit_run")
    }
    paths["split_run"] = run_root / config["split"]["floorplancad_run"] / "metrics.json"
    metrics = {
        name: json.loads(path.read_text(encoding="utf-8")) for name, path in paths.items()
    }
    parsed = metrics["parse_run"]
    split = metrics["split_run"]
    audit = metrics["split_audit_run"]
    class_audit = metrics["class_audit_run"]
    if sum(split[f"{fold}_drawings"] for fold in ("train", "val", "test")) != parsed["distinct_contents_parsed"]:
        raise ValueError("Split and parsing runs disagree on deduplicated drawing count")
    if sum(split[f"{fold}_elements"] for fold in ("train", "val", "test")) != parsed["elements_distinct_contents"]:
        raise ValueError("Split and parsing runs disagree on parsed entity count")
    output.mkdir(parents=True, exist_ok=True)

    def emit(name: str, columns: str, headers: list[str], rows: list[list[str]], source: str) -> None:
        write_table(output / name, columns, headers, rows, [str(paths[source])])

    emit("public_parse_summary.tex", "lr", ["Reported quantity", "Count"], [
        [label, number(parsed[key])]
        for label, key in [
            ("Release files", "files"),
            ("Distinct contents parsed", "distinct_contents_parsed"),
            ("Files served from cache", "files_cached"),
            ("Files failed", "files_failed"),
            ("Parsed entities, including text", "elements_distinct_contents"),
            ("Entities with semantic identifiers", "labelled_elements_distinct_contents"),
        ]
    ], "parse_run")
    emit("public_entity_kinds.tex", "lr", ["Entity kind", "Count"], [
        [label, number(parsed[f"elements_{key}"])]
        for label, key in [("Line", "line"), ("Arc", "arc"), ("Circle", "circle"), ("Ellipse", "ellipse"), ("Text", "text")]
    ], "parse_run")
    emit("public_source_audit.tex", "lr", ["Audit quantity", "Value"], [
        ["Source groups", number(audit["groups"])],
        ["Exact-duplicate content clusters", number(audit["duplicate_content_groups"])],
        ["Duplicate clusters spanning official training and test", number(audit["duplicate_groups_across_train_and_test"])],
        ["Official test files", number(audit["test_files"])],
        ["Official test files sharing a group with training", number(audit["test_files_with_group_in_train"])],
        ["Share of official test files sharing a group with training", percentage(audit["test_file_fraction_with_group_in_train"])],
    ], "split_audit_run")
    emit("public_layer_similarity.tex", "lrr", ["Release-folder pair", "Same-prefix similarity", "Random-pair similarity"], [
        [label, number(audit[f"{key}_same_prefix_layer_jaccard"]), number(audit[f"{key}_random_pair_layer_jaccard"])]
        for label, key in [
            (r"\texttt{train-00} / \texttt{train-01}", "train-00_vs_train-01"),
            (r"\texttt{train-00} / \texttt{test-00}", "train-00_vs_test-00"),
            (r"\texttt{train-01} / \texttt{test-00}", "train-01_vs_test-00"),
        ]
    ], "split_audit_run")
    folds = [("Training", "train"), ("Validation", "val"), ("Held-out", "test")]
    emit("public_folds.tex", "lrrr", ["Fold", "Drawings", "Groups", "Parsed entities"], [
        [label, number(split[f"{fold}_drawings"]), number(split[f"{fold}_groups"]), number(split[f"{fold}_elements"])]
        for label, fold in folds
    ], "split_run")
    emit("public_class_counts.tex", "lrrr", ["Fold", "Wall", "Door", "Window"], [
        [label] + [number(split[f"{fold}_{name}_elements"]) for name in ("wall", "door", "window")]
        for label, fold in folds
    ], "split_run")
    classes = config["public"]["floorplancad"]["classes"]
    write_table(output / "public_class_mapping.tex", "ll", ["Output class", "Release semantic identifiers"], [
        [name.title(), ", ".join(number(identifier) for identifier in values)]
        for name, values in classes.items()
    ] + [[r"\texttt{other}", "Remaining and missing identifiers"]], [str(args.config), "docs/decisions/0005-floorplancad-class-mapping.md"])
    wall_identifiers = classes["wall"]
    emit("public_wall_layer_evidence.tex", "lrr", ["Wall identifier", "Entities", "Share on wall layers"], [
        [number(identifier), number(class_audit[f"id{identifier:02d}_elements"]), percentage(class_audit[f"id{identifier:02d}_wall_layer_share"])]
        for identifier in wall_identifiers
    ], "class_audit_run")


if __name__ == "__main__":
    main()
